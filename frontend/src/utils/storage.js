/*
  저장 용량을 사람이 쓰는 단위로 적습니다.
  ---------------------------------------------------------------------------
  등록 화면은 1024를 '1TB'로 보여 주는데 상세 화면은 같은 값을 '1024GB'로 적어서,
  판매자가 고른 것과 구매자가 보는 것이 달랐습니다. 두 화면이 이 함수 하나를 씁니다.

  1024로 나누어떨어질 때만 TB로 적습니다. 그러지 않으면 3000GB가
  '2.9296875TB'처럼 읽을 수 없는 값이 됩니다(용량은 직접 입력도 됩니다).
*/
export function formatStorage(gb) {
  const value = Number(gb)
  if (!Number.isFinite(value) || value <= 0) return ''
  return value % 1024 === 0 ? `${value / 1024}TB` : `${value}GB`
}
